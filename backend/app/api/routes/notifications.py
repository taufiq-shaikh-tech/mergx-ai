from fastapi import APIRouter, Depends
from sqlalchemy import select, desc
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_user
from app.db.models import Notification
from app.db.session import get_db
from app.schemas.auth import UserIdentity
from app.core.response import ok

router = APIRouter(prefix="/notifications", tags=["Notifications"])


@router.get(
    "",
    summary="List User Notifications",
    description="Retrieves notifications generated by real analysis and security events.",
)
async def list_notifications(
    current_user: UserIdentity = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    stmt = select(Notification).where(Notification.user_id == current_user.id).order_by(desc(Notification.created_at))
    res = await db.execute(stmt)
    notifications = res.scalars().all()

    formatted = [
        {
            "id": n.id,
            "title": n.title,
            "description": n.description,
            "time": n.created_at.strftime("%I:%M %p") if n.created_at else "Recently",
            "read": n.read,
            "type": n.type,
        }
        for n in notifications
    ]
    return ok(data=formatted)


@router.patch(
    "/{notification_id}/read",
    summary="Mark Notification as Read",
)
async def mark_read(
    notification_id: int,
    current_user: UserIdentity = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    stmt = select(Notification).where(Notification.id == notification_id, Notification.user_id == current_user.id)
    res = await db.execute(stmt)
    notif = res.scalar_one_or_none()
    if notif:
        notif.read = True
        await db.commit()
    return ok(data={"id": notification_id, "read": True})
